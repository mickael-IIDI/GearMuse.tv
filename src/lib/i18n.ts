export const dictionaries: Record<Locale, Dict> = { fr, en };
export type Dictionary = Dict;
export const getDictionary = (locale: Locale) => dictionaries[locale] ?? fr;

/** Libellé localisé d'un objet { fr, en, … } issu de la base. */
export function label(labels: { fr: string; en?: string; [k: string]: string | undefined } | null | undefined, locale: string): string {
  if (!labels) return "";
  return labels[locale] || labels.fr;
}
